#!/usr/bin/env python3
"""Build every table, figure and quoted number from the raw run files.

    make_report.py <results dir>   ->   <results dir>/report/{tables.md,numbers.json,*.png,*.svg}

Means are over repetitions with 95% Student-t half-widths; ratios of two
configurations carry first-order error propagation, as in the uringpy paper.
"""
import collections
import glob
import json
import math
import os
import sys

from scipy import stats as sstats

SERVER_LABEL = {
    "uvicorn-httptools": "Uvicorn (httptools + uvloop)",
    "uvicorn-httptools-asyncio": "Uvicorn (httptools + asyncio)",
    "uvicorn-h11": "Uvicorn (h11 + asyncio)",
    "granian": "Granian",
    "uh-request": "uringpy-http, GIL per request",
    "uh-batch": "uringpy-http, GIL per batch",
    "uh-static": "uringpy-http, static (no Python)",
}
APP_LABEL = {"raw": "raw ASGI", "starlette_app": "Starlette", "fastapi_app": "FastAPI"}


def tq(n):
    return sstats.t.ppf(0.975, n - 1) if n > 1 else float("nan")


class Cell:
    def __init__(self, recs):
        self.recs = recs
        self.x = [r["wrk"]["rps"] for r in recs]
        self.n = len(self.x)
        self.mean = sum(self.x) / self.n if self.n else float("nan")
        self.sd = (math.sqrt(sum((v - self.mean) ** 2 for v in self.x) / (self.n - 1))
                   if self.n > 1 else 0.0)
        self.hw = tq(self.n) * self.sd / math.sqrt(self.n) if self.n > 1 else float("nan")

    def avg(self, f):
        vals = [f(r) for r in self.recs]
        vals = [v for v in vals if v is not None]
        return sum(vals) / len(vals) if vals else None

    def per_req(self, key):
        # summed counter over summed server-counted requests (or wrk's count)
        num = den = 0
        for r in self.recs:
            c = r.get("server_counters", {})
            if key not in c or c[key] is None:
                return None
            num += c[key]
            den += c.get("requests") or r["wrk"]["requests"]
        return num / den if den else None

    def per_wrk_req(self, key):
        num = den = 0
        for r in self.recs:
            c = r.get("server_counters", {})
            if c.get(key) is None:
                return None
            num += c[key]
            den += r["wrk"]["requests"]
        return num / den if den else None

    @property
    def cv(self):
        return self.sd / self.mean if self.mean else 0.0


def ratio(a, b):
    """a.mean / b.mean with a 95% half-width (first-order propagation)."""
    if a is None or b is None or not a.n or not b.n:
        return None, None
    r = a.mean / b.mean
    if a.n < 2 or b.n < 2:
        return r, None
    t = tq(min(a.n, b.n))
    hw = t * r * math.sqrt(a.sd ** 2 / (a.n * a.mean ** 2) + b.sd ** 2 / (b.n * b.mean ** 2))
    return r, hw


def fmt_r(r, hw, d=2):
    if r is None:
        return "–"
    if hw is None or hw != hw:
        return "%.*f" % (d, r)
    return "%.*f ± %.*f" % (d, r, d, hw) if hw >= 10 ** -d else "%.*f ± <%.*f" % (d, r, d, 10 ** -d)


def fmt_k(c):
    if c is None or not c.n:
        return "–"
    if c.n < 2:
        return "%.1f" % (c.mean / 1e3)
    return "%.1f ± %.1f" % (c.mean / 1e3, c.hw / 1e3)


def load(results):
    by_ex = collections.defaultdict(list)
    failed = collections.defaultdict(list)
    for path in sorted(glob.glob(os.path.join(results, "raw", "*", "*.json"))):
        ex = os.path.basename(os.path.dirname(path))
        with open(path) as fh:
            r = json.load(fh)
        r["_file"] = os.path.relpath(path, results)
        (by_ex if r.get("ok") else failed)[ex].append(r)
    return by_ex, failed


def key(r):
    return (r["build"], r["server"], r["mode"], r["app"], r["workers"], r.get("rate"))


def cells(recs):
    g = collections.defaultdict(list)
    for r in recs:
        g[key(r)].append(r)
    return {k: Cell(v) for k, v in g.items()}


def main(results):
    out = os.path.join(results, "report")
    os.makedirs(out, exist_ok=True)
    by_ex, failed = load(results)
    with open(os.path.join(results, "environment.json")) as fh:
        env = json.load(fh)
    md = []
    nums = {}
    md.append("# uringpy-http benchmark report\n")
    md.append("Generated by `bench/make_report.py` from `%s`.\n" % results)
    md.append("Server: %s. Python (GIL build): %s. Commit: %s.\n" % (
        env.get("server_nproc", "?").strip() + " CPUs", env.get("server_python_gil", "?").strip().splitlines()[0]
        if env.get("server_python_gil") else "?", env.get("server_commit", "?").strip()))
    total = sum(len(v) for v in by_ex.values())
    nfail = sum(len(v) for v in failed.values())
    md.append("Runs: %d succeeded, %d failed.\n" % (total, nfail))
    nums["runs_ok"] = total
    nums["runs_failed"] = nfail
    if nfail:
        md.append("\n## Failed runs\n\n| experiment | configuration | error |\n|---|---|---|")
        for ex, rs in failed.items():
            for r in rs:
                md.append("| %s | %s %s %s n=%d %s | %s |" % (ex, r["build"], r["server"], r["mode"],
                                                          r["workers"], r["app"], r.get("error", "")[:120]))
    errs = [(r["_file"], r["wrk"]) for rs in by_ex.values() for r in rs
            if any(r["wrk"][k] for k in ("err_connect", "err_read", "err_write", "err_status", "err_timeout"))]
    md.append("\nRuns with any wrk socket or status error: %d.\n" % len(errs))
    nums["runs_with_errors"] = len(errs)
    client_max = max((r["client_busy_share"] for rs in by_ex.values() for r in rs), default=0)
    steal_max = max((r.get("server_steal_share", 0) for rs in by_ex.values() for r in rs), default=0)
    md.append("Highest client busy share in any run: %.0f%%. Highest server steal share: %.2f%%.\n"
              % (100 * client_max, 100 * steal_max))
    nums["client_busy_max"] = client_max

    figs = {}
    if "main" in by_ex:
        figs.update(report_main(by_ex["main"], md, nums))
    if "hold" in by_ex:
        report_hold(by_ex["hold"], md, nums)
    if "ft" in by_ex:
        report_ft(by_ex["ft"], by_ex.get("main", []), md, nums)
    if "openloop" in by_ex:
        report_openloop(by_ex["openloop"], md, nums)
    with open(os.path.join(out, "tables.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(out, "numbers.json"), "w") as fh:
        json.dump(nums, fh, indent=1, sort_keys=True)
    plot(by_ex, out)
    print("wrote", out)


def report_main(recs, md, nums):
    C = cells(recs)
    ns = sorted({r["workers"] for r in recs})
    nmax = ns[-1]
    md.append("\n## Throughput (GIL build, closed loop)\n")
    md.append("Thousands of requests per second, mean ± 95%% half-width; S = x̄_%d / x̄_1; "
              "T/P = threads over processes of the same server at %d workers; "
              "c.sw. = voluntary context switches per request, g = GIL owner changes per request, "
              "C = busy server cores, all at %d workers.\n" % (nmax, nmax, nmax))
    servers = ["uvicorn-h11", "uvicorn-httptools", "granian", "uh-request", "uh-batch"]
    for app in ("raw", "starlette_app", "fastapi_app"):
        md.append("\n### %s\n" % APP_LABEL[app])
        hdr = "| server | workers | " + " | ".join("N=%d" % n for n in ns) + \
              " | S | T/P | c.sw. | g | C | p99 ms |"
        md.append(hdr)
        md.append("|" + "---|" * (hdr.count("|") - 1))
        rows = [(s, m) for s in servers for m in ("thread", "process")]
        if app == "raw":
            rows += [("uh-static", "thread"), ("uh-static", "process")]
        for s, m in rows:
            k = lambda n: ("gil", s, m, app if s != "uh-static" else "raw", n, None)
            if k(nmax) not in C:
                continue
            c1, cn = C.get(k(1)), C.get(k(nmax))
            S = ratio(cn, c1)
            other = C.get(("gil", s, "process" if m == "thread" else "thread", k(nmax)[3], nmax, None))
            tp = ratio(cn, other) if m == "thread" else (None, None)
            csw = cn.per_wrk_req("voluntary_ctx")
            g = cn.per_wrk_req("gil_switches")
            busy = cn.avg(lambda r: r["server_busy_share"] * r["server_cpus"])
            p99 = cn.avg(lambda r: r["wrk"]["lat_p99_us"] / 1000)
            md.append("| %s | %s | %s | %s | %s | %s | %s | %.2f | %.1f |" % (
                SERVER_LABEL[s], m, " | ".join(fmt_k(C.get(k(n))) for n in ns),
                fmt_r(*S), fmt_r(*tp), "%.3f" % csw if csw is not None else "–",
                "%.3f" % g if g is not None else "–", busy or 0, p99 or 0))
            base = "%s.%s.%s" % (app, s, m)
            for n in ns:
                if C.get(k(n)):
                    nums["%s.n%d.krps" % (base, n)] = round(C[k(n)].mean / 1e3, 2)
            nums[base + ".S"] = round(S[0], 3) if S[0] else None
            if tp[0]:
                nums[base + ".TP"] = round(tp[0], 3)
            if csw is not None:
                nums[base + ".csw"] = round(csw, 4)
            if g is not None:
                nums[base + ".g"] = round(g, 4)
        # headline ratios against Uvicorn run as processes (its normal deployment)
        md.append("")
        ref = C.get(("gil", "uvicorn-httptools", "process", app, nmax, None))
        ref1 = C.get(("gil", "uvicorn-httptools", "process", app, 1, None))
        for s, m in [("uh-batch", "thread"), ("uh-batch", "process"), ("uh-request", "thread"),
                     ("uh-request", "process"), ("granian", "process")]:
            c = C.get(("gil", s, m, app, nmax, None))
            c1 = C.get(("gil", s, m, app, 1, None))
            r, hw = ratio(c, ref)
            r1, hw1 = ratio(c1, ref1)
            if r:
                md.append("- %s (%s) vs Uvicorn processes: %s at %d workers, %s at 1 worker"
                          % (SERVER_LABEL[s], m, fmt_r(r, hw), nmax, fmt_r(r1, hw1)))
                nums["%s.%s.%s.vs_uvicorn_proc.n%d" % (app, s, m, nmax)] = round(r, 3)
                if r1:
                    nums["%s.%s.%s.vs_uvicorn_proc.n1" % (app, s, m)] = round(r1, 3)
        b, rq = C.get(("gil", "uh-batch", "thread", app, nmax, None)), C.get(("gil", "uh-request", "thread", app, nmax, None))
        r, hw = ratio(b, rq)
        if r:
            md.append("- GIL per batch over GIL per request, %d threads: %s" % (nmax, fmt_r(r, hw)))
            nums["%s.batch_over_request.threads.n%d" % (app, nmax)] = round(r, 3)
    return {}


def report_hold(recs, md, nums):
    C = cells(recs)
    md.append("\n## Time under the GIL per request (timing on, threads)\n")
    md.append("| app | GIL | workers | x̄ (k/s) | t_p µs | w µs | acquisitions/req | U = x̄·t_p |")
    md.append("|---|---|---|---|---|---|---|---|")
    for (b, s, m, app, n, _), c in sorted(C.items(), key=lambda kv: (kv[0][3], kv[0][1], kv[0][4])):
        hold = c.per_req("gil_hold_ns")
        wait = c.per_req("gil_wait_ns")
        acq = c.per_req("gil_acquires")
        if hold is None:
            continue
        tp_us = hold / 1e3
        md.append("| %s | %s | %d | %s | %.2f | %.2f | %.3f | %.2f |" % (
            APP_LABEL[app], "batch" if s == "uh-batch" else "request", n, fmt_k(c), tp_us,
            (wait or 0) / 1e3, acq or 0, c.mean * hold / 1e9))
        nums["hold.%s.%s.n%d.tp_us" % (app, s, n)] = round(tp_us, 3)
        nums["hold.%s.%s.n%d.w_us" % (app, s, n)] = round((wait or 0) / 1e3, 3)
        nums["hold.%s.%s.n%d.acq" % (app, s, n)] = round(acq or 0, 4)


def report_ft(recs, main_recs, md, nums):
    C = cells(recs)
    G = cells(main_recs)
    ns = sorted({r["workers"] for r in recs})
    nmax = ns[-1]
    md.append("\n## Free-threaded build\n")
    md.append("| app | server | workers | " + " | ".join("N=%d" % n for n in ns) +
              " | S | T/P | GIL actually off |")
    md.append("|" + "---|" * (6 + len(ns) - 1))
    for app in ("raw", "fastapi_app"):
        for s, m in [("uh-batch", "thread"), ("uh-request", "thread"), ("uh-batch", "process"),
                     ("uvicorn-httptools-asyncio", "thread"), ("uvicorn-httptools-asyncio", "process")]:
            k = lambda n: ("ft", s, m, app, n, None)
            if k(nmax) not in C:
                continue
            S = ratio(C[k(nmax)], C.get(k(1)))
            other = C.get(("ft", s, "process", app, nmax, None)) if m == "thread" else None
            tp = ratio(C[k(nmax)], other) if other else (None, None)
            off = sorted({str(x) for r in C[k(nmax)].recs for x in (r.get("gil_enabled") or [])})
            md.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                APP_LABEL[app], SERVER_LABEL[s], m, " | ".join(fmt_k(C.get(k(n))) for n in ns),
                fmt_r(*S), fmt_r(*tp), "yes" if off == ["False"] else ("no" if off else "–")))
            nums["ft.%s.%s.%s.S" % (app, s, m)] = round(S[0], 3) if S[0] else None
            for n in ns:
                if C.get(k(n)):
                    nums["ft.%s.%s.%s.n%d.krps" % (app, s, m, n)] = round(C[k(n)].mean / 1e3, 2)


def report_openloop(recs, md, nums):
    C = cells(recs)
    md.append("\n## Open loop (wrk2, fixed rates)\n")
    md.append("Median / 99th-percentile latency in ms (corrected for coordinated omission), "
              "and delivered rate as a share of offered; * = below 95% of the offered rate.\n")
    for app in ("raw", "fastapi_app"):
        rates = sorted({k[5] for k in C if k[3] == app})
        servers = [("uvicorn-httptools", "process"), ("uh-request", "thread"),
                   ("uh-batch", "thread"), ("uh-batch", "process")]
        md.append("\n### %s\n" % APP_LABEL[app])
        md.append("| offered | " + " | ".join("%s (%s)" % (SERVER_LABEL[s], m) for s, m in servers) + " |")
        md.append("|" + "---|" * (len(servers) + 1))
        for rate in rates:
            row = []
            for s, m in servers:
                c = C.get(("gil", s, m, app, recs[0]["workers"], rate))
                if not c:
                    row.append("–")
                    continue
                p50 = c.avg(lambda r: r["wrk"]["lat_p50_us"] / 1000)
                p99 = c.avg(lambda r: r["wrk"]["lat_p99_us"] / 1000)
                share = c.mean / rate
                row.append("%.2f / %.2f%s" % (p50, p99, "*" if share < 0.95 else ""))
                nums["ol.%s.%s.%s.R%d.p50_ms" % (app, s, m, rate)] = round(p50, 3)
                nums["ol.%s.%s.%s.R%d.p99_ms" % (app, s, m, rate)] = round(p99, 3)
                nums["ol.%s.%s.%s.R%d.share" % (app, s, m, rate)] = round(share, 3)
            md.append("| %dk | %s |" % (rate // 1000, " | ".join(row)))


def plot(by_ex, out):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    if "main" not in by_ex:
        return
    C = cells(by_ex["main"])
    ns = sorted({k[4] for k in C})
    styles = [("uvicorn-httptools", "process", "#7f7f7f", "--"), ("uvicorn-httptools", "thread", "#7f7f7f", "-"),
              ("granian", "process", "#9467bd", "--"),
              ("uh-request", "thread", "#ff7f0e", "-"), ("uh-request", "process", "#ff7f0e", "--"),
              ("uh-batch", "thread", "#1f77b4", "-"), ("uh-batch", "process", "#1f77b4", "--")]
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.8), sharey=False)
    for ax, app in zip(axes, ("raw", "starlette_app", "fastapi_app")):
        for s, m, col, ls in styles:
            pts = [(n, C[("gil", s, m, app, n, None)]) for n in ns if ("gil", s, m, app, n, None) in C]
            if not pts:
                continue
            ax.errorbar([n for n, _ in pts], [c.mean / 1e3 for _, c in pts],
                        yerr=[0 if c.hw != c.hw else c.hw / 1e3 for _, c in pts],
                        color=col, ls=ls, marker="o" if m == "thread" else "s",
                        mfc=col if m == "thread" else "white", capsize=2,
                        label="%s, %ss" % (SERVER_LABEL[s], m))
        ax.set_title(APP_LABEL[app])
        ax.set_xlabel("workers N")
        ax.set_xticks(ns)
        ax.set_ylim(bottom=0)
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("thousand requests per second")
    axes[0].legend(fontsize=6.5, loc="upper left")
    fig.tight_layout()
    for ext in ("png", "svg", "pdf"):
        fig.savefig(os.path.join(out, "fig_throughput.%s" % ext), dpi=200)
    plt.close(fig)


if __name__ == "__main__":
    main(sys.argv[1])
